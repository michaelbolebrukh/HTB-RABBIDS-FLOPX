def _offers(rng: random.Random) -> list[dict]:
    offers = []
    counter = 0
    for provider in PROVIDERS:
        # Each provider lists in 4-5 regions and 3-4 models, so ~60 offers total:
        regions = rng.sample(REGIONS, 4 if provider["kind"] != "hyperscaler" else 5)
        models = rng.sample(GPU_MODELS, 3 if provider["kind"] == "marketplace" else 2)
        for region in regions:
            for model in models:
                counter += 1
                contract = rng.choices(["on-demand", "reserved", "spot"], weights=[6, 2, 2])[0]
                if provider["kind"] == "hyperscaler" and contract == "spot":
                    contract = "on-demand"
                if provider["kind"] == "marketplace" and contract == "reserved":
                    contract = "spot"
                base = BASE_PRICE[model["id"]] * provider["factor"] * region["factor"]
                noise = rng.uniform(0.93, 1.07)
                multiplier = {"on-demand": 1.0, "reserved": 0.70, "spot": 0.45}[contract]
                price = round(base * noise * multiplier, 2)
                availability = rng.choices(["available", "limited", "unavailable"], weights=[6, 3, 1])[0]
                offers.append({
                    "id": f"offer-{counter:03d}",
                    "providerId": provider["id"],
                    "regionId": region["id"],
                    "gpuModelId": model["id"],
                    "gpuCount": rng.choice([1, 8, 8, 16, 64, 128]),
                    "pricePerGpuHourUsd": price,
                    "availability": availability,
                    "interruptible": contract == "spot",
                    "contract": contract,
                    "reliabilityScore": round(rng.uniform(0.86, 0.995), 3) if provider["kind"] != "hyperscaler" else None,
                    "bandwidthGbps": rng.choice([25, 100, 200, 400, 3200]) if model["interconnect"] == "NVLink" else rng.choice([10, 25, 100]),
                    "minDurationHours": {"on-demand": 1, "reserved": 720, "spot": None}[contract],
                    "provenance": {"kind": "sample", "source": SOURCE, "observedAt": _iso(SNAPSHOT_AT),
                                   "note": "authored sample offer; advertised ask, not utilisation"},
                })
    return offers


def _previous_offers(rng: random.Random, offers: list[dict]) -> list[dict]:
    """The snapshot a week earlier, with authored differences change detection must find."""
    week_ago = SNAPSHOT_AT - timedelta(days=7)
    previous = []
    for offer in offers:
        copy = json.loads(json.dumps(offer))
        copy["provenance"]["observedAt"] = _iso(week_ago)
        previous.append(copy)
    # Authored differences (ids are stable across the two snapshots):
    moves = {"offer-003": 1.09, "offer-011": 0.91, "offer-027": 1.15, "offer-040": 0.88}
    for row in previous:
        if row["id"] in moves:
            row["pricePerGpuHourUsd"] = round(row["pricePerGpuHourUsd"] / moves[row["id"]], 2)
        if row["id"] == "offer-015":
            row["availability"] = "available" if row["availability"] != "available" else "limited"
    # One offer that existed last week and is gone now, one that is new this week:
    removed = json.loads(json.dumps(previous[5]))
    removed["id"] = "offer-900"
    removed["pricePerGpuHourUsd"] = round(removed["pricePerGpuHourUsd"] * 0.97, 2)
    previous.append(removed)
    previous = [row for row in previous if row["id"] != "offer-058"]
    return previous


def _series(rng: random.Random) -> list[dict]:
    """Monthly (24) + daily (180) GPU price history per model, daily sample closes per ticker."""
    series = []
    for model in GPU_MODELS:
        level = BASE_PRICE[model["id"]]
        # Monthly: a gentle decline over two years toward today's level, mild noise:
        monthly = []
        for k in range(24):
            t = (SNAPSHOT_AT.replace(day=1) - timedelta(days=30 * (23 - k)))
            trend = level * (1.0 + 0.55 * ((23 - k) / 23.0))        # 55% higher two years ago
            monthly.append([_iso(t), round(trend * rng.uniform(0.97, 1.03), 3)])
        series.append({"id": f"gpu:{model['id']}:on-demand:global:monthly", "unit": "USD/GPU-hour", "points": monthly})
        # Daily: random walk with slight downward drift, weekly seasonality, ending at today's level:
        daily_values = []
        value = level * 1.06
        for day in range(180):
            drift = -0.00035 * value
            shock = rng.gauss(0, 0.011) * value
            value = max(0.05, value + drift + shock)
            daily_values.append(value)
        scale = level / daily_values[-1]
        daily = []
        for day, v in enumerate(daily_values):
            t = SNAPSHOT_AT - timedelta(days=179 - day)
            seasonal = 1.0 + 0.012 * math.sin(2 * math.pi * (t.weekday() / 7.0))
            daily.append([_iso(t), round(v * scale * seasonal, 3)])
        series.append({"id": f"gpu:{model['id']}:on-demand:global", "unit": "USD/GPU-hour", "points": daily})
    for company in COMPANIES:
        value = company["close"] * rng.uniform(0.7, 1.3)
        closes = []
        for day in range(180):
            value = max(1.0, value * (1 + rng.gauss(0.0006, 0.028)))
            closes.append(value)
        scale = company["close"] / closes[-1]
        points = [[_iso(SNAPSHOT_AT - timedelta(days=179 - d)), round(v * scale, 2)] for d, v in enumerate(closes)]
        series.append({"id": f"equity:{company['ticker']}:close", "unit": "USD", "points": points})
    # One energy indicator so the map's energy layer and the scenario lab have an input:
    energy = []
    for day in range(180):
        t = SNAPSHOT_AT - timedelta(days=179 - day)
        energy.append([_iso(t), round(38 + 9 * math.sin(day / 11.0) + rng.gauss(0, 4), 2)])
    series.append({"id": "energy:ERCOT:day-ahead", "unit": "USD/MWh", "points": energy})
    return series


