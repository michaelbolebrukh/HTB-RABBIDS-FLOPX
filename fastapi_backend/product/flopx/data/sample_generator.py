def _feed(rng: random.Random, facilities: list[dict], offers: list[dict]) -> list[dict]:
    items = []
    region_names = {r["id"]: r["name"] for r in REGIONS}
    for i in range(1, 41):
        kind, classification, severity, headline_t, why_t = rng.choice(FEED_TEMPLATES)
        facility = rng.choice(facilities)
        gpu = rng.choice(GPU_MODELS)
        provider = rng.choice(PROVIDERS)
        ticker = rng.choice(TICKERS)
        region = rng.choice(REGIONS)
        pct = f"{rng.choice([-1, 1]) * rng.uniform(2.5, 11.0):+.1f}%"
        fill = {"facility": facility["name"], "mw": facility["capacityMw"], "region": region_names[region["id"]],
                "gpu": gpu["id"], "provider": provider["name"], "ticker": ticker, "pct": pct, "grid": region["gridZone"]}
        published = SNAPSHOT_AT - timedelta(hours=rng.randint(1, 24 * 40))
        offer = rng.choice(offers)
        items.append({
            "id": f"intel-{i:03d}",
            "kind": kind,
            "headline": headline_t.format(**fill),
            "whyItMatters": why_t.format(**fill),
            "publishedAt": _iso(published),
            "observedAt": _iso(published - timedelta(hours=rng.randint(0, 6))),
            "geography": {"regionIds": [region["id"]]},
            "entities": {"tickers": [ticker] if kind in ("earnings", "divergence", "announcement") else [],
                         "facilityIds": [facility["id"]] if kind in ("announcement", "policy", "power-event") else [],
                         "gpuModelIds": [gpu["id"]] if kind in ("price-move", "supply-anomaly", "prediction-reprice", "launch", "divergence") else [],
                         "marketIds": [f"mkt-{rng.randint(1, 12):03d}"] if kind == "prediction-reprice" else []},
            "severity": max(1, min(5, severity + rng.choice([-1, 0, 0, 1]))),
            "evidence": [
                {"label": "sample offer", "href": f"/gpu?tab=offers&offer={offer['id']}", "kind": "offer"},
                {"label": "sample series", "href": f"/research?tab=lab&series=gpu:{gpu['id']}:on-demand:global", "kind": "series"},
            ],
            "classification": classification,
            "scenarioSeed": {"target": f"gpu:{gpu['id']}:on-demand:global", "assumptions": {"supplyGrowthPct": rng.choice([-10, 5, 10, 20])}} if kind in ("announcement", "power-event", "policy") else None,
            "provenance": {"kind": "sample", "source": SOURCE, "observedAt": _iso(published),
                           "note": "authored sample intelligence item; the headline describes no real event"},
        })
    items.sort(key=lambda item: item["publishedAt"], reverse=True)
    return items


def generate() -> dict[str, dict]:
    rng = random.Random(SEED)
    offers = _offers(rng)
    previous = _previous_offers(rng, offers)
    facilities = _facilities(rng)
    files = {
        "gpu_models.json": {"provenance": _prov("GPU model reference sheet: public spec-sheet values, authored."), "items": GPU_MODELS},
        "providers.json": {"provenance": _prov("Fictional providers so sample prices are never read as a real vendor's quote."),
                           "items": [{k: v for k, v in p.items() if k != "factor"} for p in PROVIDERS]},
        "regions.json": {"provenance": _prov("Well-known data-centre hubs; each region is the catchment its sample facilities are assigned to, and power stress reads the hub's grid zone. Coordinates are public geography."),
                         "items": [{k: v for k, v in r.items() if k != "factor"} for r in REGIONS]},
        "gpu_offers.json": {"provenance": _prov("Current sample offer snapshot (advertised asks, authored)."), "items": offers},
        "gpu_offers_previous.json": {"provenance": _prov("Sample offer snapshot seven days earlier, authored to contain detectable changes."), "items": previous},
        "facilities.json": {"provenance": _prov("Sample facilities on public data-centre geographies; every attached value is authored."), "items": facilities},
        "companies.json": {"provenance": _prov("Eight listed compute names with general profile text and authored sample reference values."), "items": _companies(rng, facilities)},
        "markets.json": {"provenance": _prov("Twelve prediction-market-style questions, authored; no real contract."), "items": _markets(rng)},
        "feed.json": {"provenance": _prov("Forty authored intelligence items describing no real event."), "items": _feed(rng, facilities, offers)},
        "series.json": {"provenance": _prov("24 monthly + 180 daily sample points per GPU model, 180 daily sample closes per ticker, one energy indicator."), "items": _series(rng)},
    }
    return files


def write(sample_dir: Path = SAMPLE_DIR) -> list[Path]:
    sample_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, payload in generate().items():
        path = sample_dir / name
        path.write_text(json.dumps(payload, indent=1, sort_keys=False) + "\n", encoding="utf-8")
        written.append(path)
    return written


