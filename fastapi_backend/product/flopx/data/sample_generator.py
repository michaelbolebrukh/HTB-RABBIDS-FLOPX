"""Deterministic generator for the FLOPX SAMPLE datasets (architecture §7).

Run from `fastapi_backend/`:

    .venv/bin/python -m product.flopx.data.sample_generator

Rewrites every file under `product/flopx/data/sample/`. The generator is
seeded, so the output is reproducible and reviewable as a diff; the files are
committed because the loader reads files, never this module, at runtime.

Everything here is AUTHORED. Numbers are chosen to sit at plausible late-2026
market levels (an H100 SXM between roughly $2.0 and $4.5 per GPU-hour on
demand) so the terminal reads like a terminal, but no value was observed
anywhere. Providers are fictional on purpose, so a sample price can never be
mistaken for a real vendor's quote. Facilities use the coordinates of
well-known data-centre regions (public geography) with sample status, capacity
and ownership values; they describe no real company's footprint. Every file
carries a top-level `provenance` block saying exactly this.
"""

