"""The generic admin notification: one reusable template for operator alerts.

Purpose-specific operator emails (contact form, the payment family) each earn a
template because their shape is rich - info rows, references, amounts. Everything
else an internal feature wants to tell the operators is a heading, a few
paragraphs, maybe a severity tag and a link - so it goes through THIS one
template (`admin_notification`, authored in
next-pwa/platform/emails/components/admin-notification.tsx and generated by
`npm run build:emails` like every other template) instead of minting a new
template type per event.

Recipient resolution matches the existing operator alerts (contact_service and
payment_services.notification_service): the ops inbox `CONTACT_EMAIL`, which is
derived from APP_DOMAIN and always set. Deliberately NOT ADMIN_EMAIL - that is
the admin user's personal login address used for seeding, not a notification
destination.

Delivery is synchronous and RAISES on failure (EmailSendException), so each
caller decides its own failure policy - a webhook path wraps it in a background
task, a request path that must never break wraps it in try/except. This module
does not swallow errors on the caller's behalf.
"""

import logging
from typing import Optional, Sequence

from platform.enums import EmailTemplateType
from platform.services.email_services import send_templated_email
from infrastructure.settings import settings as s


logger = logging.getLogger(__name__)


def _ops_headers(topic: str) -> dict[str, str]:
    """Standards-based signals letting the ops inbox filter automated alerts.

    The same List-Id (RFC 2919) + Auto-Submitted (RFC 3834) pair the payment
    alerts carry, so one recipient-side rule routes every automated notification
    out of the main inbox. `topic` scopes the List-Id per alert family.
    """
    domain = s.APP_DOMAIN or "localhost"
    return {
        "List-Id": f"{s.SENDER_NAME or 'Admin'} alerts <{topic}.admin.{domain}>",
        "Auto-Submitted": "auto-generated",
    }


def send_admin_notification(
    *,
    subject: str,
    body_lines: Sequence[str],
    heading: Optional[str] = None,
    severity: Optional[str] = None,
    cta_url: Optional[str] = None,
    cta_label: Optional[str] = None,
    topic: str = "general",
    tags: Optional[list[str]] = None,
) -> None:
    """Sends the generic operator notification to the ops inbox.

    - `body_lines` render as paragraphs (joined with blank lines; the template
      preserves the breaks via white-space: pre-line).
    - `severity` is an optional short tag ("warning", "critical") shown as a
      chip above the heading; omitted = no chip.
    - `cta_url`/`cta_label` render one button; both or neither.
    - `topic` scopes the List-Id header so alert families are filterable apart.

    Raises EmailSendException (or the provider's error) on failure - callers on
    paths that must never break wrap this themselves.
    """
    recipient = s.CONTACT_EMAIL
    if not recipient:
        # CONTACT_EMAIL is derived from APP_DOMAIN so this is near-unreachable,
        # but a silent no-send must still leave a trace:
        logger.warning("Admin notification '%s' dropped: no CONTACT_EMAIL configured.", subject)
        return

    send_templated_email(
        template_type=EmailTemplateType.ADMIN_NOTIFICATION,
        recipient=recipient,
        headers=_ops_headers(topic),
        tags=["admin-notification", *(tags or [])],
        subject=subject,
        heading=heading or subject,
        body="\n\n".join(body_lines),
        # Optional template sections hide themselves on falsy values ({% if %}
        # in the generated template), so None simply renders nothing:
        severity=severity,
        # A boolean rather than a template-side string comparison: the template
        # is generated from React, whose text-node escaping would mangle quoted
        # literals inside a Jinja expression. "critical" renders the danger
        # chip; every other tag renders the warning one.
        severity_critical=bool(severity) and severity.strip().lower() == "critical",
        cta_url=cta_url,
        cta_label=cta_label or "Open",
    )
